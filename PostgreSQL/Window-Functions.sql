-- WINDOW FUNCTIONS

-- 1. AGGREGATE

CREATE TABLE SALES(
	TRANSACTION_ID INT,
    STORE VARCHAR(20),
    SALES_AMOUNT DECIMAL(10,2)
);

INSERT INTO SALES
VALUES(1,'A',100.00),(2,'A',200.00),(3,'A',150.00),(4,'B',250.00),(5,'B',300.00);

SELECT * FROM SALES;

SELECT STORE,SUM(SALES_AMOUNT) AS AMOUNT FROM SALES
GROUP BY STORE; -- RESULTANT ROWS SHRINK

SELECT 
	TRANSACTION_ID,STORE,SALES_AMOUNT,
    SUM(SALES_AMOUNT) OVER()
FROM SALES; -- CALCULATE SUM AND INSERT EVERY ROW

SELECT 
	TRANSACTION_ID,STORE,SALES_AMOUNT,
    SUM(SALES_AMOUNT) OVER(PARTITION BY STORE) AS TOTAL
FROM SALES; -- STORE WISE SUM ADDED FOR EVERY ROW

SELECT
	TRANSACTION_ID,STORE,SALES_AMOUNT,
	SUM(SALES_AMOUNT) OVER(PARTITION BY STORE ORDER BY SALES_AMOUNT) AS TOTAL
FROM SALES; -- STORE WISE SUM ADDED IN INCREMENTAL WAY

-- 2. RANKING WINDOW FUNCTIONS

-- (i). ROW_NUMBER()

SELECT
	TRANSACTION_ID,STORE,SALES_AMOUNT,
	ROW_NUMBER() OVER()
FROM SALES;

SELECT
	TRANSACTION_ID,STORE,SALES_AMOUNT,
	ROW_NUMBER() OVER(ORDER BY SALES_AMOUNT DESC)
FROM SALES;

SELECT
	TRANSACTION_ID,STORE,SALES_AMOUNT,
	ROW_NUMBER() OVER(PARTITION BY STORE)
FROM SALES;

SELECT
	TRANSACTION_ID,STORE,SALES_AMOUNT,
	ROW_NUMBER() OVER(PARTITION BY STORE ORDER BY SALES_AMOUNT ASC)
FROM SALES;

-- (ii). RANK(), DENSE_RANK()

CREATE TABLE STUDENT_WINDOW(
	 STUDENT_ID INT,
     STUDENT_NAME VARCHAR(20),
     SCORE INT
);

INSERT INTO STUDENT_WINDOW
VALUES
(1, 'ALICE', 95),
(2, 'BOB', 90),
(3, 'CHARLIE', 95),
(4, 'DAVID', 85),
(5, 'EVA', 90);

SELECT *,
	RANK() OVER(ORDER BY SCORE DESC)
FROM STUDENT_WINDOW;

SELECT *,
	DENSE_RANK() OVER(ORDER BY SCORE DESC)
FROM STUDENT_WINDOW;

-- (iii). PERCENT_RANK() - FORMULA -> RANK OF THE ROW - 1 / TOTAL NUMBER OF ROWS - 1

SELECT *,
	PERCENT_RANK() OVER(ORDER BY SCORE DESC)
FROM STUDENT_WINDOW;

