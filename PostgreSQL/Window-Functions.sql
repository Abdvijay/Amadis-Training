-- (iv). LAST_VALUE()

SELECT
	EMPLOYEEID,EMPLOYEENAME,YEAR,SALARY,
    LAST_VALUE(SALARY) OVER(PARTITION BY EMPLOYEEID ORDER BY YEAR 
    ROWS BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING) AS LATEST_SALARY
FROM EMPLOYEE_SALARY;


SELECT
	EMPLOYEEID,EMPLOYEENAME,YEAR,SALARY AS YEAR_WISE_SALARY,
    FIRST_VALUE(SALARY) OVER(PARTITION BY EMPLOYEEID ORDER BY YEAR) AS FIRST_SALARY,
    LAST_VALUE(SALARY) OVER(PARTITION BY EMPLOYEEID ORDER BY YEAR 
    ROWS BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING) AS LATEST_SALARY,
    LAST_VALUE(SALARY) OVER(PARTITION BY EMPLOYEEID ORDER BY YEAR 
    ROWS BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING) - SALARY AS SALARY_DIFF_BY_CURRENT_TO_YEAR_WISE
FROM EMPLOYEE_SALARY;

-- (v). NTH_VALUE()

