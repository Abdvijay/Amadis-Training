-- 3. VALUE WINDOW FUNCTION

-- (i). LAG()


CREATE TABLE EMPLOYEE_VALUE_WINDOW(
	EMPLOYEE_ID INT,
    EMPLOYEE_NAME VARCHAR(20),
    SALARY DECIMAL(10,2),
    YEAR VARCHAR(10)
);

INSERT INTO EMPLOYEE_VALUE_WINDOW
VALUES
(1, 'Alice', 5000.00, 2023),
(1, 'Alice', 5500.00, 2024),
(2, 'Bob', 4500.00, 2023),
(2, 'Bob', 4800.00, 2024),
(3, 'Charlie', 4000.00, 2023),
(3, 'Charlie', 4200.00, 2024),
(4, 'David', 4600.00, 2023),
(5,'Eva',5200.00,2023),
(5,'Eva',5400.00,2024);

SELECT 
	EMPLOYEE_ID,EMPLOYEE_NAME,SALARY,YEAR,
    LAG(SALARY) OVER(PARTITION BY EMPLOYEE_ID ORDER BY YEAR) AS PREV_SALARY,
    SALARY - LAG(SALARY) OVER(PARTITION BY EMPLOYEE_ID ORDER BY YEAR) AS INCR_SALARY
FROM EMPLOYEE_VALUE_WINDOW;

