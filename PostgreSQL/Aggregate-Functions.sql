SELECT DEPARTMENT, STRING_AGG(EMPLOYEE_NAME,', ') FROM EMPLOYEES GROUP BY DEPARTMENT;
SELECT STRING_AGG(DISTINCT DEPARTMENT, ', ') FROM EMPLOYEES;

-- 8. CASE WHEN THEN

SELECT EMPLOYEE_NAME,SALARY,
	CASE
		WHEN SALARY >= 70000 THEN 'HIGH SALARY'
		WHEN SALARY >= 50000 THEN 'MEDIUM'
		ELSE 'LOW'
	END AS SALARY_CATEGORY
FROM EMPLOYEES;

SELECT EMPLOYEE_NAME,JOINING_DATE,
	CASE
		WHEN AGE < 23 THEN 'JUNIOR'
		WHEN AGE BETWEEN 23 AND 27 THEN 'MID LEVEL'
		ELSE 'SENIOR'
	END AS CATEGORY
FROM EMPLOYEES;

SELECT SUM(CASE WHEN DEPARTMENT = 'IT' THEN SALARY ELSE 0 END) FROM EMPLOYEES;

SELECT EMPLOYEE_NAME,SALARY,DEPARTMENT FROM EMPLOYEES
	ORDER BY
		CASE
			WHEN DEPARTMENT = 'IT' THEN 1
			WHEN DEPARTMENT = 'HR' THEN 2
			ELSE 3
		END;

SELECT EMPLOYEE_NAME,
