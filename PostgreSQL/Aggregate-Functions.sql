-- 1. GROUP BY EXPRESSION
SELECT 
	CASE
		WHEN SALARY >= 60000 THEN 'HIGH SALARY'
		ELSE 'LOW SALARY'
	END AS SALARY_CATEGORY,
	COUNT(*) AS TOTAL_EMPLOYEES
FROM EMPLOYEES
GROUP BY 
	CASE
		WHEN SALARY >= 60000 THEN 'HIGH SALARY'
		ELSE 'LOW SALARY'
	END;

SELECT
	CASE
		WHEN AGE < 25 THEN 'FRESHER'
		ELSE 'EXPERIENCED'
	END AS CATEGORY,
	COUNT(*)
FROM EMPLOYEES
GROUP BY
	CASE
		WHEN AGE < 25 THEN 'FRESHER'
		ELSE 'EXPERIENCED'
	END;

-- 2. GROUP BY COLUMN POSITION

SELECT DEPARTMENT,COUNT(*) AS TOTAL_EMPLOYEES FROM EMPLOYEES
	GROUP BY DEPARTMENT;

SELECT DEPARTMENT,COUNT(*) AS TOTAL_EMPLOYEES FROM EMPLOYEES
	GROUP BY 1;

SELECT DEPARTMENT,AGE,COUNT(*) FROM EMPLOYEES
	GROUP BY 1,2;

-- 3. GROUP BY DATE_TRUNC()

SELECT DATE_TRUNC('month', JOINING_DATE) AS JOINING_MONTH, COUNT(*) AS TOTAL_EMPLOYEES FROM EMPLOYEES
	GROUP BY DATE_TRUNC('month', JOINING_DATE)
	ORDER BY JOINING_MONTH;

SELECT DATE_TRUNC('year', JOINING_DATE) AS JOINING_YEAR, COUNT(*) FROM EMPLOYEES
	GROUP BY DATE_TRUNC('year', JOINING_DATE);

-- 4. GROUP BY WITH NUMERIC FUNCTION

SELECT ROUND(SALARY) AS ROUNDED_SALARY, COUNT(*) FROM EMPLOYEES
	GROUP BY ROUND(SALARY)
	ORDER BY ROUNDED_SALARY;

SELECT (AGE/10)*10 AS AGE_GROUP, COUNT(*) FROM EMPLOYEES
	GROUP BY (AGE/10)*10
	ORDER BY AGE_GROUP;

-- 5. GROUP BY WITHOUT AGGREGATION

SELECT DEPARTMENT FROM EMPLOYEES GROUP BY DEPARTMENT;

-- 6. CONDITIONAL AGGREGATION

SELECT COUNT(*) FILTER(WHERE DEPARTMENT = 'IT') AS IT_EMPLOYEES FROM EMPLOYEES;
SELECT
	COUNT(*) FILTER(WHERE DEPARTMENT = 'Finance') AS FINANCE_EMPLOYEES,
	COUNT(*) FILTER(WHERE DEPARTMENT = 'HR') AS HR_EMPLOYEES
FROM EMPLOYEES;
SELECT SUM(SALARY) FILTER(WHERE DEPARTMENT = 'IT') AS TOTAL_SALARY_OF_IT FROM EMPLOYEES;
SELECT MIN(SALARY) FILTER(WHERE DEPARTMENT = 'Finance') as LOWEST_OF_FINANCE FROM EMPLOYEES;
SELECT MAX(SALARY) FILTER(WHERE DEPARTMENT = 'HR') AS HIGHEST_OF_HR FROM EMPLOYEES;

-- 7. STRING AGGREGATION

